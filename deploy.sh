#!/usr/bin/env bash
#
# Aagasa ground station deployment.
#
#   ./deploy.sh up        start everything (builds first if no images exist)
#   ./deploy.sh down      stop and remove the containers; data is kept
#   ./deploy.sh restart   down, then up
#   ./deploy.sh rebuild   rebuild the web client and the images, then restart
#   ./deploy.sh reset     delete the database and station state, rebuild, start
#
# Missing env files are created on first run: secrets are generated and the
# station-specific details are asked for. 'up' also makes the station start at
# boot (a systemd user service); 'down' turns that off again.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SERVER_ENV="$ROOT/deploy/server/.env.server"
WORKER_ENV="$ROOT/deploy/worker/.env.worker"
DATA="${AAGASA_DATA_DIR:-$ROOT/data}"
NETWORK="aagasa-net"
PODS=(aagasa-worker-pod aagasa-server-pod aagasa-databases)
UNIT="aagasa.service"
UNIT_FILE="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/$UNIT"
# Set by the systemd unit, so boot-time runs never change the boot setting.
FROM_SYSTEMD="${AAGASA_FROM_SYSTEMD:-}"

say()  { printf '\n== %s\n' "$1"; }
note() { printf '   %s\n' "$1"; }
warn() { printf '!! %s\n' "$1" >&2; }
die()  { printf 'deploy: %s\n' "$1" >&2; exit 1; }

# ---------------------------------------------------------------- env files

ask() {  # ask "question" default -> answer (the default when not interactive)
    local answer=""
    if [[ -t 0 ]]; then
        read -r -p "   $1 [$2]: " answer
    fi
    printf '%s' "${answer:-$2}"
}

ask_number() {  # ask_number "question" default min max
    local value
    while true; do
        value="$(ask "$1" "$2")"
        if [[ "$value" =~ ^[0-9]+$ ]] && ((value >= $3 && value <= $4)); then
            printf '%s' "$value"
            return
        fi
        printf '   enter a whole number from %s to %s\n' "$3" "$4" >&2
        [[ -t 0 ]] || die "invalid default for: $1"
    done
}

env_value() { sed -n "s/^$2=//p" "$1" 2>/dev/null | tail -1; }

secret() { od -An -N24 -tx1 /dev/urandom | tr -d ' \n'; }

ensure_env() {
    [[ -f "$SERVER_ENV" && -f "$WORKER_ENV" ]] && return

    say "Creating missing configuration"
    local shared
    shared="$(env_value "$SERVER_ENV" AAGASA_WORKER_SHARED_SECRET)"
    shared="${shared:-$(env_value "$WORKER_ENV" AAGASA_WORKER_SHARED_SECRET)}"
    shared="${shared:-$(secret)}"

    if [[ ! -f "$SERVER_ENV" ]]; then
        if [[ -d "$DATA/postgres" ]]; then
            die "$SERVER_ENV is missing but a database exists in $DATA/postgres;
   its password is unknown. Restore the env file, or run './deploy.sh reset'."
        fi
        write_server_env "$(secret)" "$shared"
        note "wrote $SERVER_ENV"
    fi
    if [[ ! -f "$WORKER_ENV" ]]; then
        note "Station details (press Enter to keep the value in brackets):"
        write_worker_env "$shared"
        note "wrote $WORKER_ENV"
    fi
}

write_server_env() {  # postgres_password shared_secret
    (umask 077; cat > "$SERVER_ENV") <<EOF || die "cannot write $SERVER_ENV"
# Aagasa server. Generated by deploy.sh; secrets are random.
AAGASA_ENV=development
AAGASA_LOG_LEVEL=info

AAGASA_HTTP_ADDRESS=:8080
AAGASA_GRPC_ADDRESS=:9090

AAGASA_POSTGRES_URL=postgres://aagasa:$1@aagasa-databases:5432/aagasa?sslmode=disable
AAGASA_REDIS_URL=redis://aagasa-databases:6379/0
AAGASA_MONGO_URL=mongodb://aagasa-databases:27017
AAGASA_MONGO_DATABASE=aagasa

AAGASA_PREDICTION_ADDRESS=127.0.0.1:9091

AAGASA_CELESTRAK_URL=
AAGASA_SATNOGS_URL=
AAGASA_TLE_REFRESH_ENABLED=true

AAGASA_RECORDINGS_DIR=/var/lib/aagasa/recordings
AAGASA_PIPELINES_DIR=/var/lib/aagasa/pipelines
AAGASA_WEB_DIR=/app/web

AAGASA_WORKER_SHARED_SECRET=$2

AAGASA_STARTUP_TIMEOUT=10
AAGASA_SESSION_TTL=43200

# Where the web UI and API are published on this host. 0.0.0.0 serves the
# local network; 127.0.0.1 keeps it on this machine (e.g. behind an HTTPS
# reverse proxy, which is how to expose the station beyond a trusted LAN).
AAGASA_PUBLISH_ADDRESS=0.0.0.0
EOF
}

write_worker_env() {  # shared_secret
    local name port baud azimuth elevation sdr
    name="$(ask "Worker name (enter the same name in the app's Setup)" "worker-1")"
    port="$(ask "Rotator serial port" "/dev/ttyUSB0")"
    baud="$(ask_number "Rotator baud rate" 9600 1 4000000)"
    azimuth="$(ask_number "Rotator park azimuth (0-359)" 0 0 359)"
    elevation="$(ask_number "Rotator park elevation (0-90)" 0 0 90)"
    sdr="$(ask_number "RTL-SDR device index" 0 0 15)"

    (umask 077; cat > "$WORKER_ENV") <<EOF || die "cannot write $WORKER_ENV"
# Aagasa worker. Generated by deploy.sh.
AAGASA_LOG_LEVEL=info

AAGASA_WORKER_NAME=$name

AAGASA_SERVER_GRPC_ADDRESS=aagasa-server-pod:9090
AAGASA_SERVER_TLS_ENABLED=false

AAGASA_WORKER_SHARED_SECRET=$1

AAGASA_STATE_DIR=/var/lib/aagasa/state
AAGASA_RECORDINGS_DIR=/var/lib/aagasa/recordings

AAGASA_ROTATOR_SERIAL_PORT=$port
AAGASA_ROTATOR_BAUD_RATE=$baud
AAGASA_ROTATOR_PARK_AZIMUTH=$azimuth
AAGASA_ROTATOR_PARK_ELEVATION=$elevation

AAGASA_SDR_DEVICE_INDEX=$sdr
AAGASA_RTL_TEST_BIN=rtl_test

AAGASA_SATDUMP_BIN=satdump
AAGASA_SATDUMP_PIPELINES_DIR=/usr/local/share/satdump/resources/pipelines
AAGASA_SATDUMP_LEGACY_CLI=true

AAGASA_HEARTBEAT_INTERVAL_SECONDS=5
EOF
}

postgres_password() {
    local url
    url="$(env_value "$SERVER_ENV" AAGASA_POSTGRES_URL)"
    url="${url#*://aagasa:}"
    printf '%s' "${url%%@*}"
}

# ------------------------------------------------------------------- build

install_web() {
    say "Installing the web client"
    local web_src=""
    local candidate
    for candidate in "$ROOT/client/build/web" "$ROOT/client/web"; do
        if [[ -f "$candidate/main.dart.js" && -f "$candidate/index.html" ]]; then
            web_src="$candidate"
            break
        fi
    done
    [[ -n "$web_src" ]] \
        || die "no complete built web client found; run 'flutter build web' or put the built files in client/web"
    rm -rf "$ROOT/deploy/server/web"
    mkdir -p "$ROOT/deploy/server/web"
    cp -a "$web_src/." "$ROOT/deploy/server/web/"
    [[ -f "$ROOT/deploy/server/web/index.html" && -f "$ROOT/deploy/server/web/main.dart.js" ]] \
        || die "the web client copy is incomplete"
}

web_hash() {
    (cd "$ROOT/deploy/server/web" && find . -type f -print0 | sort -z | xargs -0 sha256sum | sha256sum | cut -d' ' -f1) \
        || die "cannot hash the web client"
}

build() {
    command -v podman >/dev/null || die "podman is required"
    [[ -f "$ROOT/deploy/worker/satdump.deb" ]] \
        || die "deploy/worker/satdump.deb is required; put the SatDump .deb there"
    ensure_stubs
    install_web

    local hash
    hash="$(web_hash)"
    cd "$ROOT" || die "cannot enter $ROOT"
    say "Building the server image"
    podman build --label "aagasa.web.hash=$hash" -f deploy/server/Containerfile -t aagasa-server:latest . \
        || die "server image build failed"
    say "Building the prediction image"
    podman build -f deploy/server/Containerfile.prediction -t aagasa-prediction:latest . \
        || die "prediction image build failed"
    say "Building the worker image"
    podman build -f deploy/worker/Containerfile -t aagasa-worker:latest . \
        || die "worker image build failed"
}

# The gRPC stubs are generated, not hand-written; make them on a fresh clone.
ensure_stubs() {
    [[ -d "$ROOT/server/go/internal/gen/worker" && -d "$ROOT/worker/src/aagasa/worker" \
        && -d "$ROOT/server/python/src/aagasa/prediction" ]] && return

    say "Generating gRPC stubs"
    command -v protoc >/dev/null && command -v uv >/dev/null \
        || die "protoc and uv are needed to generate the gRPC stubs"
    local worker_protos=(proto/aagasa/worker/v1/worker.proto
        proto/aagasa/worker/v1/passplan.proto proto/aagasa/worker/v1/recording.proto)
    cd "$ROOT" || die "cannot enter $ROOT"
    mkdir -p server/go/internal/gen
    protoc -I proto \
        --go_out=server/go/internal/gen --go_opt=module=aagasa/internal/gen \
        --go-grpc_out=server/go/internal/gen --go-grpc_opt=module=aagasa/internal/gen \
        proto/aagasa/prediction/v1/prediction.proto "${worker_protos[@]}" \
        || die "protoc (Go) failed"
    (cd server/python && uv run python -m grpc_tools.protoc -I ../../proto \
        --python_out=src --grpc_python_out=src --pyi_out=src \
        ../../proto/aagasa/prediction/v1/prediction.proto) || die "protoc (prediction) failed"
    (cd worker && uv run python -m grpc_tools.protoc -I ../proto \
        --python_out=src --grpc_python_out=src --pyi_out=src \
        "${worker_protos[@]/#proto/../proto}") || die "protoc (worker) failed"
}

images_exist() {
    local image
    for image in aagasa-server aagasa-prediction aagasa-worker; do
        podman image exists "localhost/$image:latest" || return 1
    done
}

# ------------------------------------------------------------------ run

wait_for() {  # wait_for "what" command...
    local what="$1"; shift
    for _ in $(seq 60); do
        "$@" >/dev/null 2>&1 && return 0
        sleep 2
    done
    die "$what did not become ready"
}

server_ready() {
    curl -fsS --max-time 3 http://127.0.0.1:8080/readyz | grep -q '"status":"ready"'
}

running() {
    local pod
    for pod in "${PODS[@]}"; do
        [[ "$(podman pod inspect --format '{{.State}}' "$pod" 2>/dev/null)" == "Running" ]] \
            || return 1
    done
}

start() {
    command -v podman >/dev/null || die "podman is required"
    if running; then
        note "already running at http://127.0.0.1:8080; use './deploy.sh restart' to restart"
        return
    fi
    ensure_env
    install_web
    local image_hash
    image_hash="$(podman image inspect --format '{{index .Config.Labels "aagasa.web.hash"}}' \
        localhost/aagasa-server:latest 2>/dev/null || true)"
    if ! images_exist || [[ "$image_hash" != "$(web_hash)" ]]; then
        build
    fi
    stop >/dev/null  # clear anything left over from a half-finished start

    mkdir -p "$DATA"/{postgres,mongo,redis,recordings,pipelines,worker-state}
    podman unshare chown -R 0:0 "$DATA/worker-state" 2>/dev/null || true
    chmod a+rwX "$DATA"/{redis,recordings,pipelines,worker-state} 2>/dev/null || true
    podman network exists "$NETWORK" || podman network create "$NETWORK" >/dev/null

    say "Databases"
    local rendered
    rendered="$(mktemp)"
    sed -e "s|/var/lib/aagasa|$DATA|g" \
        -e "s|__POSTGRES_PASSWORD__|$(postgres_password)|" \
        "$ROOT/deploy/server/databases.yaml" > "$rendered"
    podman kube play --network "$NETWORK" "$rendered" >/dev/null
    local played=$?
    rm -f "$rendered"
    [[ $played -eq 0 ]] || die "the database pod did not start"
    wait_for "postgres" podman exec aagasa-databases-postgres pg_isready -U aagasa

    say "Database schema"
    local migrate=(podman run --rm --network "$NETWORK" --env-file "$SERVER_ENV"
        localhost/aagasa-server:latest aagasa-migrate)
    "${migrate[@]}" up >/dev/null || die "postgres migration failed"
    "${migrate[@]}" mongo-init >/dev/null || die "mongo init failed"

    say "Server"
    # Only the web UI/API is published. The worker reaches gRPC (9090) over
    # the internal podman network, so it is never exposed on the host.
    local publish
    publish="$(env_value "$SERVER_ENV" AAGASA_PUBLISH_ADDRESS)"
    publish="${publish:-0.0.0.0}"
    podman pod create --name aagasa-server-pod --network "$NETWORK" \
        -p "$publish:8080:8080" >/dev/null
    podman run -d --pod aagasa-server-pod --name aagasa-prediction --restart=always \
        --env-file "$SERVER_ENV" localhost/aagasa-prediction:latest >/dev/null
    # The host's tz database, read-only: Debian tzdata updates reach the time
    # zone list without a rebuild. Never relabelled; it is a system directory.
    local tz=()
    [[ -f /usr/share/zoneinfo/zone1970.tab ]] && tz=(-v /usr/share/zoneinfo:/usr/share/zoneinfo:ro)
    podman run -d --pod aagasa-server-pod --name aagasa-server --restart=always \
        --env-file "$SERVER_ENV" \
        -v "$DATA/recordings:/var/lib/aagasa/recordings:Z" \
        -v "$DATA/pipelines:/var/lib/aagasa/pipelines:Z" \
        "${tz[@]}" localhost/aagasa-server:latest >/dev/null
    wait_for "the server (podman logs aagasa-server)" server_ready

    say "Worker"
    local port devices=()
    port="$(env_value "$WORKER_ENV" AAGASA_ROTATOR_SERIAL_PORT)"
    if [[ -n "$port" && -e "$port" ]]; then
        devices+=(-v "$port:$port")
    else
        warn "no rotator at ${port:-<unset>}; passes will record without pointing"
    fi
    [[ -d /dev/bus/usb ]] && devices+=(-v /dev/bus/usb:/dev/bus/usb)
    lsusb 2>/dev/null | grep -qi -E '0bda:283[28]' \
        || warn "no RTL-SDR on USB; passes will fail until one is plugged in"
    lsmod 2>/dev/null | grep -q '^dvb_usb_rtl28xxu' \
        && warn "kernel driver dvb_usb_rtl28xxu is loaded and can block the RTL-SDR"

    podman pod create --name aagasa-worker-pod --network "$NETWORK" \
        --userns=keep-id:uid=10003,gid=10003 >/dev/null
    podman run -d --pod aagasa-worker-pod --name aagasa-worker --restart=always \
        --env-file "$WORKER_ENV" -e HOME=/home/aagasa \
        -v "$DATA/worker-state:/var/lib/aagasa/state:Z" \
        -v "$DATA/recordings:/var/lib/aagasa/recordings:Z" \
        "${devices[@]}" localhost/aagasa-worker:latest

    [[ -n "$FROM_SYSTEMD" ]] || enable_boot

    say "Running"
    note "Web UI and API: http://$publish:8080"
    note "Data:           $DATA"
    note "Logs:           podman logs -f aagasa-server   (or aagasa-worker)"
}

# ------------------------------------------------------------------- boot

enable_boot() {
    command -v systemctl >/dev/null || { warn "no systemd; the station will not start at boot"; return; }
    mkdir -p "$(dirname "$UNIT_FILE")"
    cat > "$UNIT_FILE" <<UNIT_EOF
# Installed by $ROOT/deploy.sh. Starts the Aagasa station at boot.
[Unit]
Description=Aagasa ground station
Wants=network-online.target
After=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
Environment=AAGASA_FROM_SYSTEMD=1
Environment=PATH=$PATH
ExecStart=$ROOT/deploy.sh up
ExecStop=$ROOT/deploy.sh down
TimeoutStartSec=900

[Install]
WantedBy=default.target
UNIT_EOF
    systemctl --user daemon-reload && systemctl --user enable "$UNIT" >/dev/null 2>&1 \
        || { warn "could not enable $UNIT; the station will not start at boot"; return; }
    # Without lingering, user services only run while the user is logged in.
    if [[ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" != "yes" ]] \
        && ! loginctl enable-linger "$USER" 2>/dev/null; then
        warn "to start at boot without logging in, run once: sudo loginctl enable-linger $USER"
        return
    fi
    note "starts at boot ($UNIT)"
}

disable_boot() {
    [[ -f "$UNIT_FILE" ]] || return 0
    systemctl --user disable "$UNIT" >/dev/null 2>&1
    rm -f "$UNIT_FILE"
    systemctl --user daemon-reload 2>/dev/null
    note "no longer starts at boot"
}

stop() {
    command -v podman >/dev/null || die "podman is required"
    local pod
    for pod in "${PODS[@]}"; do
        podman pod exists "$pod" && podman pod rm -f "$pod" >/dev/null
    done
    podman network exists "$NETWORK" && podman network rm "$NETWORK" >/dev/null 2>&1
    note "stopped; data kept in $DATA"
}

reset() {
    if [[ "${1:-}" != "--yes" ]]; then
        [[ -t 0 ]] || die "reset deletes the database; run './deploy.sh reset --yes' to confirm"
        printf 'This deletes the database, all accounts, the station setup and the\n'
        printf "worker's state in %s (recordings are kept).\n" "$DATA"
        local answer
        read -r -p "Type 'reset' to continue: " answer
        [[ "$answer" == "reset" ]] || die "cancelled"
    fi
    say "Stopping"
    stop
    say "Deleting the database and station state"
    # Database files belong to container users, so delete them inside the
    # user namespace that owns them.
    podman unshare rm -rf "$DATA/postgres" "$DATA/mongo" "$DATA/worker-state" \
        || die "could not delete $DATA"
    note "deleted"
    build
    start
}

case "${1:-}" in
    up)      start ;;
    down)    say "Stopping"; stop; [[ -n "$FROM_SYSTEMD" ]] || disable_boot ;;
    restart) say "Stopping"; stop; start ;;
    rebuild) build; say "Stopping"; stop; start ;;
    reset)   reset "${2:-}" ;;
    *)
        sed -n '3,12p' "$0" | sed 's/^# \{0,1\}//'
        [[ -z "${1:-}" || "$1" == "help" || "$1" == "-h" || "$1" == "--help" ]] || exit 1
        ;;
esac
